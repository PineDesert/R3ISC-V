    mem[3] = 32'h0030A223; // SW   x3, 0(x1)
    mem[4] = 32'h0000A283; // LW   x5, 0(x1)
    mem[5] = 32'h0051A333; // AND  x6, x3, x5
    mem[6] = 32'h0051A3B3; // OR   x7, x3, x5
    mem[7] = 32'h00528463; // BEQ  x5, x5, +8
