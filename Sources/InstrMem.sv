    mem[11] = 32'h00000013;
    mem[12] = 32'h00000013;
    mem[13] = 32'h00000013;
    mem[14] = 32'h00000013;
    mem[15] = 32'h00000013;
  end

  assign readData = mem[addr[31 : 2]]; //word alligned

endmodule